"""Prompt templates and builders for the Agent Service."""

from app.agent.schemas import AnalysisPlan
from app.datasets.schemas import DatasetProfile


# ── System prompt ────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """\
You are an expert analytical planning engine for structured tabular data.

Your task is to read a user's analytical question together with a dataset profile
and produce a single, valid JSON object conforming to the AnalysisPlan schema below.

Rules you MUST follow:
1. Respond with ONLY a valid JSON object — no explanation, no markdown, no extra text.
2. Every column name you reference MUST exist verbatim in the dataset schema provided.
3. Every aggregation type MUST be one of: sum, avg, mean, count, min, max, median.
4. Every operation type MUST be one of: aggregation, filtering, ranking, summary, trend.
5. Every filter operator MUST be one of: eq, neq, gt, gte, lt, lte, in, not_in, between, year, month.
6. Every visualization type MUST be one of: bar, line, scatter, histogram, pie.
7. The "question" field must contain the original user question verbatim.
8. Do NOT invent column names that are not in the schema.
9. Do NOT produce SQL, Python code, or explanations — only the JSON plan.

AnalysisPlan JSON Schema:
{schema}
""".strip()


def build_system_prompt() -> str:
    """Build the system prompt, injecting the current AnalysisPlan JSON schema."""
    schema = AnalysisPlan.json_schema_for_llm()
    return SYSTEM_PROMPT.format(schema=schema)


# ── User prompt ───────────────────────────────────────────────────────────────

_USER_PROMPT_TEMPLATE = """\
Dataset Profile:
{profile_context}

User Question:
{question}

Respond with a JSON object that represents the AnalysisPlan for this question.
Use ONLY column names that appear in the dataset profile above.
""".strip()


def build_plan_prompt(question: str, profile: DatasetProfile) -> str:
    """
    Build the user-turn prompt from a question and dataset profile.

    Args:
        question: The user's natural-language analytical question.
        profile: The DatasetProfile generated by the DatasetProfiler.

    Returns:
        Formatted prompt string ready to send to the LLM.
    """
    return _USER_PROMPT_TEMPLATE.format(
        profile_context=profile.to_llm_context_str(),
        question=question,
    )


# ── Retry prompt ──────────────────────────────────────────────────────────────

_RETRY_PROMPT_TEMPLATE = """\
Your previous response failed validation with the following error:

Error:
{error_message}

Your previous response was:
{previous_output}

Please correct the JSON and respond with a valid AnalysisPlan object only.
Remember: respond with ONLY a valid JSON object, no extra text.
""".strip()


def build_retry_prompt(error_message: str, previous_output: str) -> str:
    """
    Build a self-correction prompt from the validation error and prior LLM output.

    Args:
        error_message: The validation or parse error message from the previous attempt.
        previous_output: The raw string the LLM produced on the previous attempt.

    Returns:
        Formatted retry prompt string.
    """
    return _RETRY_PROMPT_TEMPLATE.format(
        error_message=error_message,
        previous_output=previous_output,
    )
